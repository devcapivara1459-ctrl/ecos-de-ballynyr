import {test,expect,request} from '@playwright/test';
const base=process.env.TEST_BASE_URL||'http://localhost:3000';
const origin={Origin:new URL(base).origin};
test('jornada completa, recuperação, segurança e seis atribuições concorrentes',async({browser})=>{
 const admin=await request.newContext({baseURL:base,extraHTTPHeaders:origin});
 const outsider=await request.newContext({baseURL:base,extraHTTPHeaders:origin});
 expect((await outsider.get('/api/admin/invites')).status()).toBe(401);
 expect((await outsider.post('/api/admin/session',{data:{key:'wrong'}})).status()).toBe(401);
 expect((await admin.post('/api/admin/session',{data:{key:process.env.ADMIN_KEY}})).ok()).toBeTruthy();
 const temporary=await admin.post('/api/admin/invites',{data:{name:'Convite a revogar'}});
 const temporaryUrl=(await temporary.json()).url;
 const temporaryRows=(await (await admin.get('/api/admin/invites')).json()).invites;
 expect((await admin.patch('/api/admin/invites',{data:{id:temporaryRows[0].id,action:'revoke'}})).ok()).toBeTruthy();
 expect((await outsider.post('/api/quiz/state',{data:{token:temporaryUrl.split('/').pop()}})).status()).toBe(404);
 expect((await outsider.post('/api/quiz/start',{data:{token:temporaryUrl.split('/').pop(),name:'Intruso'}})).status()).toBe(409);
 const created=await admin.post('/api/admin/invites',{data:{name:'Jogador de teste'}});expect(created.status()).toBe(201);
 let url=(await created.json()).url;
 let records=(await (await admin.get('/api/admin/invites')).json()).invites;
 const id=records.find((r:{status:string})=>r.status==='new').id;
 const rotated=await admin.patch('/api/admin/invites',{data:{id,action:'rotate'}});expect(rotated.ok()).toBeTruthy();
 expect((await outsider.post('/api/quiz/start',{data:{token:url.split('/').pop(),name:'Outro'}})).status()).toBe(409);
 url=(await rotated.json()).url;let token=url.split('/').pop();
 const context=await browser.newContext({baseURL:base,viewport:{width:390,height:844},reducedMotion:'reduce'});
 let page=await context.newPage();const pageErrors:string[]=[];page.on('pageerror',e=>pageErrors.push(e.message));
 await page.goto('/');await expect(page.getByRole('heading',{name:/ECOS DE/})).toBeVisible();
 await page.screenshot({path:'test-results/home-mobile.png',fullPage:true});
 await page.goto(url);await expect(page.getByRole('button',{name:'Atender ao chamado'})).toBeEnabled();
 const sessionBeforeStart=(await context.cookies()).find(c=>c.name.startsWith('ecos_'))?.value;
 expect(sessionBeforeStart).toBeTruthy();
 await page.getByRole('button',{name:'Atender ao chamado'}).click();
 await expect(page.getByText('ESCOLHA 01')).toBeVisible();
 expect((await context.cookies()).find(c=>c.name.startsWith('ecos_'))?.value).toBe(sessionBeforeStart);
 const hidden=await page.content();expect(hidden).not.toContain('Rhiona');expect(hidden).not.toContain('Malik');
 expect((await context.request.get(`/api/portrait?id=rhiona&token=${token}`)).status()).toBe(403);
 expect((await outsider.post('/api/quiz/start',{data:{token,name:'Intruso'}})).status()).toBe(409);
 expect((await context.request.post('/api/quiz/submit',{headers:origin,data:{token,answers:[0]}})).status()).toBe(400);
 await page.getByRole('button',{name:/A Procuro marcas/}).click();await page.getByRole('button',{name:'Continuar'}).click();
 await expect(page.getByText('ESCOLHA 02')).toBeVisible();await page.reload();await expect(page.getByText('ESCOLHA 02')).toBeVisible();
 // Lose the original browser session, then let the master authorize recovery.
 expect((await outsider.post('/api/quiz/recover',{data:{token}})).status()).toBe(401);
 const originalSession=(await context.cookies()).find(c=>c.name.startsWith('ecos_'))!.value;
 await context.clearCookies();await page.reload();
 await expect(page.getByText('Este convite já foi iniciado, mas a sessão não foi encontrada neste navegador.',{exact:false})).toBeVisible();
 await page.getByLabel('Chave do mestre para autorizar a retomada').fill(process.env.ADMIN_KEY!);
 await page.getByRole('button',{name:'Autorizar retomada neste navegador'}).click();
 await expect(page.getByText('ESCOLHA 02')).toBeVisible();
 const recoveredSession=(await context.cookies()).find(c=>c.name.startsWith('ecos_')&&c.name!=='ecos_admin')!;
 expect(recoveredSession.value).not.toBe(originalSession);
 const stale=await request.newContext({baseURL:base,extraHTTPHeaders:{...origin,Cookie:`${recoveredSession.name}=${originalSession}`}});
 expect((await stale.post('/api/quiz/state',{data:{token}})).status()).toBe(409);
 expect((await stale.post('/api/quiz/submit',{data:{token,answers:Array(12).fill(0)}})).status()).toBe(409);
 await stale.dispose();
 await page.screenshot({path:'test-results/question-mobile.png',fullPage:true});
 for(let i=1;i<12;i++){
  await expect(page.getByText(`ESCOLHA ${String(i+1).padStart(2,'0')}`)).toBeVisible();
  await page.locator('.choice').first().click();await page.getByRole('button',{name:i===11?'Revelar meu destino':'Continuar'}).click();
 }
 await expect(page.getByText('A NÉVOA RECONHECE VOCÊ')).toBeVisible();
 const img=page.locator('.portrait');await expect(img).toBeVisible();await expect.poll(()=>img.evaluate((el:HTMLImageElement)=>el.complete&&el.naturalWidth>0)).toBeTruthy();
 await page.screenshot({path:'test-results/reveal-mobile.png',fullPage:true});
 const first=(await (await context.request.post('/api/quiz/submit',{headers:origin,data:{token,answers:Array(12).fill(0)}})).json()).character.id;
 const repeat=await context.request.post('/api/quiz/submit',{headers:origin,data:{token,answers:Array(12).fill(1)}});
 expect((await repeat.json()).character.id).toBe(first);
 await page.reload();await expect(page.getByText('A NÉVOA RECONHECE VOCÊ')).toBeVisible();
 expect((await outsider.post('/api/quiz/state',{data:{token}})).status()).toBe(409);
 expect((await outsider.get(`/api/portrait?id=${first}&token=${token}`)).status()).toBe(401);
 expect((await admin.patch('/api/admin/invites',{data:{id,action:'rotate'}})).status()).toBe(409);
 expect((await admin.post('/api/quiz/recover',{data:{token}})).status()).toBe(409);
 const extra=await Promise.all(Array.from({length:8},(_,i)=>admin.post('/api/admin/invites',{data:{name:`Concorrente ${i}`}})));
 expect(extra.filter(r=>r.status()===201)).toHaveLength(5);expect(extra.filter(r=>r.status()===409)).toHaveLength(3);
 const links=await Promise.all(extra.filter(r=>r.status()===201).map(async r=>(await r.json()).url));
 const players=await Promise.all(links.map(async l=>{const p=await request.newContext({baseURL:base,extraHTTPHeaders:origin});const t=l.split('/').pop();expect((await p.post('/api/quiz/start',{data:{token:t,name:'Teste simultâneo'}})).ok()).toBeTruthy();return {p,t};}));
 const results=await Promise.all(players.map(async({p,t})=>{const attempts=await Promise.all([0,1].map(()=>p.post('/api/quiz/submit',{data:{token:t,answers:Array(12).fill(0)}})));expect(attempts.every(r=>r.ok())).toBeTruthy();const ids=await Promise.all(attempts.map(async r=>(await r.json()).character.id));expect(new Set(ids).size).toBe(1);return ids[0];}));
 expect(new Set([first,...results]).size).toBe(6);
 const report=await (await admin.get('/api/admin/invites')).json();expect(report.invites.filter((i:{status:string})=>i.status==='completed')).toHaveLength(6);
 const desktop=await browser.newContext({baseURL:base,viewport:{width:1440,height:1000}});const dp=await desktop.newPage();await dp.goto('/');await dp.screenshot({path:'test-results/home-desktop.png',fullPage:true});
 await desktop.addCookies((await admin.storageState()).cookies);await dp.goto('/admin');await expect(dp.getByRole('heading',{name:'Os seis caminhos'})).toBeVisible();
 await expect.poll(()=>dp.locator('.character-image img').evaluateAll((imgs:HTMLImageElement[])=>imgs.every(i=>i.complete&&i.naturalWidth>0))).toBeTruthy();
 await dp.screenshot({path:'test-results/admin-desktop.png',fullPage:true});
 await page.setViewportSize({width:320,height:740});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 expect(pageErrors).toEqual([]);
 expect((await admin.post('/api/admin/invites',{headers:{Origin:'https://evil.example'},data:{name:'Ataque'}})).status()).toBe(403);
 await admin.delete('/api/admin/session');expect((await admin.get('/api/admin/invites')).status()).toBe(401);
 for(const {p} of players)await p.dispose();await outsider.dispose();await admin.dispose();await context.close();await desktop.close();
});

